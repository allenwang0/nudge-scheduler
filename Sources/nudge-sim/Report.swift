import Foundation
import NudgeScheduler

/// Static HTML report with inline SVG. No external scripts or stylesheets.
enum Report {
    static let ringStyle: [Ring: (cssVar: String, dash: String)] = [
        .inner: ("--ring-inner", ""), .close: ("--ring-close", "6 4"), .outer: ("--ring-outer", "2 3"),
        .distant: ("--muted", ""),
    ]

    static func esc(_ s: String) -> String {
        s.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
    }

    static func hhmm(_ minute: Int) -> String { String(format: "%02d:%02d", minute / 60, minute % 60) }

    static func html(_ r: Results) -> String {
        let main = r.main
        let capViews = r.sweep.map { run in
            """
            <div class="capview" data-cap="\(run.dailyCap)"\(run.dailyCap == r.defaultCap ? "" : " hidden")>
            \(stripSection(run))
            \(waitSection(run, r))
            \(deliverySection(run, title: "Delivery time of day, cap \(run.dailyCap), quiet 22:00 to 08:00"))
            </div>
            """
        }.joined(separator: "\n")
        let options = r.sweep.map {
            "<option value=\"\($0.dailyCap)\"\($0.dailyCap == r.defaultCap ? " selected" : "")>\($0.dailyCap)\($0.dailyCap == r.defaultCap ? " (default)" : "")</option>"
        }.joined()
        return """
            <!doctype html>
            <html lang="en">
            <head>
            <meta charset="utf-8">
            <meta name="viewport" content="width=device-width, initial-scale=1">
            <title>Nudge Scheduler Report</title>
            <style>\(css)</style>
            </head>
            <body>
            <main>
            <h1>Nudge scheduler: one simulated year</h1>
            <p class="banner">Synthetic data: 40 invented contacts, seed \(r.seed), 365 days of 2026 in America/Los_Angeles. The simulated user opens the app once a day at a random minute and replies to a nudge with probability \(main.replyProbability).</p>
            \(compareSection(r))
            <section>
            <h2>Daily cap sweep, seeds \(r.seed) to \(r.seed + UInt64(r.sweepSeeds) - 1)</h2>
            <p class="takeaway">\(esc(sweepTakeaway(r)))</p>
            \(sweepChart(r))
            </section>
            <div class="controls"><label for="cap">Show cap</label> <select id="cap">\(options)</select>
            <span class="hint">Views below follow this cap. Points on the sweep chart also select it.</span></div>
            \(capViews)
            <section>
            \(deliverySection(r.nightShift, title: "Quiet 01:00 to 07:00, this package"))
            \(deliverySection(r.nightShiftLegacy, title: "Quiet 01:00 to 07:00, legacy planner"))
            </section>
            <footer>Generated by <code>swift run -c release nudge-sim --seed \(r.seed) --out site</code>. Raw numbers: <a href="results.json">results.json</a>.</footer>
            </main>
            <div id="tip" role="tooltip" hidden></div>
            <script>\(script)</script>
            </body>
            </html>

            """
    }

    static func sweepTakeaway(_ r: Results) -> String {
        let point = r.pooledSweep[r.defaultCap - 1]
        let slow = r.slowestPooledRing(point)
        let p90 = r.pooledSweep.map { $0.stats(slow).p90Wait }
        return
            "Pooled over \(r.sweepSeeds) seeds, the \(slow.name) ring's p90 wait is \(days(p90[r.defaultCap - 1])) at cap \(r.defaultCap), "
            + "\(p90[0]) at cap 1 and \(p90[9]) at cap 10."
    }

    // MARK: Before and after table

    static func compareSection(_ r: Results) -> String {
        let main = r.main
        let rows = Results.driftRings.map { ring in
            let now = main.summary(for: ring)!
            let old = r.legacy.summary(for: ring)!
            func f(_ v: Int?) -> String { v.map(String.init) ?? "none" }
            return
                "<tr><th scope=\"row\">\(ring.name)</th><td>\(f(now.medianWait))</td><td>\(f(old.medianWait))</td><td>\(f(now.maxWaitIncludingOpen))</td><td>\(f(old.maxWaitIncludingOpen))</td><td>\(now.censored)</td><td>\(old.censored)</td></tr>"
        }.joined()
        return """
            <section>
            <h2>This package against the legacy behavior, cap 3</h2>
            <p class="takeaway">Legacy quiet-hour violations with quiet 01:00 to 07:00: \(r.nightShiftLegacy.quietHourViolations) of \(r.nightShiftLegacy.deliveries.count) deliveries; this package: \(r.nightShift.quietHourViolations) of \(r.nightShift.deliveries.count). Slots spent on a second nudge for the same contact: \(r.legacy.duplicateSlots) legacy, \(main.duplicateSlots) now.</p>
            <div class="scroll"><table>
            <thead><tr><th scope="col">Ring</th><th scope="col">Median wait, now (days)</th><th scope="col">Median, legacy</th><th scope="col">Max wait, now</th><th scope="col">Max, legacy</th><th scope="col">Never nudged, now</th><th scope="col">Never nudged, legacy</th></tr></thead>
            <tbody>\(rows)</tbody></table></div>
            <p class="note">Wait is days from the first overdue day to the first nudge. Max includes episodes still open at year end. Legacy: hard cap 3, drift priority capped at 80, no per-contact dedupe, snoozes that never expire, and the original same-day window arithmetic.</p>
            </section>
            """
    }

    // MARK: View 1, overdue strip

    static func stripSection(_ run: SimulationResult) -> String {
        let day = 2.0, rowH = 10.0, left = 46.0, top = 18.0
        let order = run.contacts.indices.sorted { (run.contacts[$0].ring, $0) < (run.contacts[$1].ring, $1) }
        let width = left + Double(run.days) * day + 4
        let height = top + Double(order.count) * rowH + 22
        var svg = ""
        let ticksByContact = Dictionary(grouping: run.deliveries.filter { $0.contact >= 0 }, by: \.contact)
        for (row, i) in order.enumerated() {
            let c = run.contacts[i]
            let y = top + Double(row) * rowH
            svg += "<g class=\"row\" data-ring=\"\(c.ring.name)\">"
            svg += "<text x=\"\(left - 4)\" y=\"\(y + 8)\" text-anchor=\"end\" class=\"lbl\">\(c.id)</text>"
            let levels = run.overdue[i]
            var d = 0
            while d < levels.count {
                let b = bucket(levels[d])
                var e = d
                while e + 1 < levels.count && bucket(levels[e + 1]) == b { e += 1 }
                if b > 0 {
                    let tip = "\(c.id) (\(c.ring.name)), days \(d + 1) to \(e + 1), \(levels[d] - 1) to \(levels[e] - 1) days overdue"
                    svg +=
                        "<rect x=\"\(left + Double(d) * day)\" y=\"\(y + 1)\" width=\"\(Double(e - d + 1) * day)\" height=\"\(rowH - 2)\" class=\"h\(b)\" data-tip=\"\(esc(tip))\"/>"
                }
                d = e + 1
            }
            for t in ticksByContact[i] ?? [] {
                svg +=
                    "<rect x=\"\(left + Double(t.day) * day)\" y=\"\(y)\" width=\"1.5\" height=\"\(rowH)\" class=\"tick\" data-tip=\"\(c.id) nudged on day \(t.day + 1) (\(t.kind)) at \(hhmm(t.minuteOfDay))\"/>"
            }
            svg += "</g>"
        }
        for m in 0..<12 {
            let x = left + Double(monthStart[m]) * day
            svg += "<text x=\"\(x)\" y=\"\(top - 6)\" class=\"lbl\">\(months[m])</text>"
        }
        svg +=
            "<text x=\"\(left)\" y=\"\(height - 4)\" class=\"lbl\">Day of 2026. Shade: days overdue, faintest 1 to 7, then 8 to 21, 22 to 60, strongest over 60. Dark tick: nudge delivered.</text>"
        let filters = Ring.allCases.map {
            "<label><input type=\"checkbox\" data-ring-filter=\"\($0.name)\" checked> \($0.name)</label>"
        }.joined(separator: " ")
        let starved = run.waits.filter(\.censored).count
        let takeaway =
            starved == 0
            ? "Every overdue contact was nudged before the year ended."
            : "\(starved) overdue episode\(starved == 1 ? "" : "s") never got a nudge before the year ended."
        return """
            <section>
            <h2>Who is overdue, and when they get nudged</h2>
            <p class="takeaway">\(takeaway)</p>
            <div class="filters">Rings: \(filters)</div>
            <div class="scroll strip"><svg width="\(width)" height="\(height)" viewBox="0 0 \(width) \(height)" role="img" aria-label="Overdue strip, one row per contact">\(svg)</svg></div>
            </section>
            """
    }

    static let months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
    static let monthStart = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334]

    static func bucket(_ level: Int) -> Int {
        switch level {
        case 0: 0
        case 1...8: 1
        case 9...22: 2
        case 23...61: 3
        default: 4
        }
    }

    // MARK: View 2, wait by ring

    static func waitSection(_ run: SimulationResult, _ r: Results) -> String {
        let waits = run.waits
        guard !waits.isEmpty else {
            return "<section><h2>Wait from overdue to nudge</h2><p class=\"empty\">No nudges in this run.</p></section>"
        }
        let w = 640.0, h = 300.0, left = 48.0, bottom = 36.0, top = 12.0
        let yMax = niceMax(waits.map(\.days).max()!)
        func y(_ v: Double) -> Double { top + (h - top - bottom) * (1 - v / yMax) }
        let band = (w - left) / 3
        var svg = axisY(yMax: yMax, y: y, left: left, width: w, label: "days")
        for (k, ring) in Results.driftRings.enumerated() {
            let cx = left + band * (Double(k) + 0.5)
            let style = ringStyle[ring]!
            for (j, wt) in waits.filter({ $0.ring == ring }).enumerated() {
                let jitter = (Double((j * 37) % 21) - 10) * band / 50
                let tip =
                    "\(run.contacts[wt.contact].id) (\(ring.name)): \(wt.days) days\(wt.censored ? ", still waiting at year end" : "")"
                let fill = wt.censored ? "none" : "var(\(style.cssVar))"
                svg +=
                    "<circle cx=\"\(cx + jitter)\" cy=\"\(y(Double(wt.days)))\" r=\"4\" fill=\"\(fill)\" stroke=\"var(\(style.cssVar))\" stroke-width=\"1.5\" class=\"dot\" data-tip=\"\(esc(tip))\"/>"
            }
            if let s = run.summary(for: ring), let med = s.medianWait {
                svg +=
                    "<line x1=\"\(cx - band / 4)\" x2=\"\(cx + band / 4)\" y1=\"\(y(Double(med)))\" y2=\"\(y(Double(med)))\" class=\"median\"/>"
                svg += "<text x=\"\(cx + band / 4 + 4)\" y=\"\(y(Double(med)) + 4)\" class=\"lbl\">median \(med)</text>"
            }
            svg +=
                "<text x=\"\(cx)\" y=\"\(h - 14)\" text-anchor=\"middle\" class=\"lbl\">\(ring.name) (every \(ring.defaultCadenceDays!) d)</text>"
        }
        let slow = r.slowestRing(run)
        return """
            <section>
            <h2>Wait from overdue to nudge, cap \(run.dailyCap)</h2>
            <p class="takeaway">Longest wait: \(r.maxWait(run, slow)) days (\(slow.name) ring). Hollow dots were still waiting when the year ended.</p>
            <svg viewBox="0 0 \(w) \(h)" role="img" aria-label="Wait in days by ring">\(svg)</svg>
            </section>
            """
    }

    /// Smallest axis top of the form 4 * step, with step in 1, 2, 5, 10, 25, 50..., so all 5 ticks are integers.
    static func niceMax(_ v: Int) -> Double {
        let steps = [1, 2, 5, 10, 25, 50, 100, 250, 500, 1000, 2500, 5000]
        return Double(4 * (steps.first { 4 * $0 >= v } ?? steps.last!))
    }

    static func axisY(yMax: Double, y: (Double) -> Double, left: Double, width: Double, label: String) -> String {
        var s = ""
        for i in 0...4 {
            let v = yMax * Double(i) / 4
            s += "<line x1=\"\(left)\" x2=\"\(width)\" y1=\"\(y(v))\" y2=\"\(y(v))\" class=\"grid\"/>"
            s += "<text x=\"\(left - 6)\" y=\"\(y(v) + 4)\" text-anchor=\"end\" class=\"lbl\">\(Int(v))</text>"
        }
        s +=
            "<text x=\"12\" y=\"\(y(yMax / 2))\" transform=\"rotate(-90 12 \(y(yMax / 2)))\" text-anchor=\"middle\" class=\"lbl\">\(label)</text>"
        return s
    }

    // MARK: View 3, delivery time of day

    static func deliverySection(_ run: SimulationResult, title: String) -> String {
        guard !run.deliveries.isEmpty else {
            return "<h3>\(esc(title))</h3><p class=\"empty\">No nudges in this run.</p>"
        }
        let quiet = try! QuietHours(startMinute: run.quietStartMinute, endMinute: run.quietEndMinute)
        var counts = Array(repeating: 0, count: 24)
        var inside = Array(repeating: 0, count: 24)
        for d in run.deliveries {
            counts[d.minuteOfDay / 60] += 1
            if d.insideQuietHours { inside[d.minuteOfDay / 60] += 1 }
        }
        let w = 640.0, h = 220.0, left = 48.0, bottom = 34.0, top = 10.0
        let yMax = niceMax(counts.max()!)
        func y(_ v: Double) -> Double { top + (h - top - bottom) * (1 - v / yMax) }
        let bw = (w - left) / 24
        var svg = ""
        for hour in 0..<24 where quiet.contains(minuteOfDay: hour * 60) {
            svg += "<rect x=\"\(left + Double(hour) * bw)\" y=\"\(top)\" width=\"\(bw)\" height=\"\(h - top - bottom)\" class=\"quiet\"/>"
        }
        svg += axisY(yMax: yMax, y: y, left: left, width: w, label: "deliveries")
        for hour in 0..<24 where counts[hour] > 0 {
            let cls = inside[hour] > 0 ? "bar bad" : "bar"
            svg +=
                "<rect x=\"\(left + Double(hour) * bw + 1)\" y=\"\(y(Double(counts[hour])))\" width=\"\(bw - 2)\" height=\"\(y(0) - y(Double(counts[hour])))\" rx=\"2\" class=\"\(cls)\" data-tip=\"\(hhmm(hour * 60)) to \(hhmm(hour * 60 + 59)): \(counts[hour]) deliveries\(inside[hour] > 0 ? ", \(inside[hour]) inside quiet hours" : "")\"/>"
        }
        for hour in stride(from: 0, to: 24, by: 3) {
            svg += "<text x=\"\(left + Double(hour) * bw + bw / 2)\" y=\"\(h - 18)\" text-anchor=\"middle\" class=\"lbl\">\(hour)</text>"
        }
        svg +=
            "<text x=\"\(left + (w - left) / 2)\" y=\"\(h - 2)\" text-anchor=\"middle\" class=\"lbl\">hour of day (local), shaded = quiet hours</text>"
        let bad = (0..<24).filter { inside[$0] > 0 }
        let takeaway =
            bad.isEmpty
            ? "0 of \(run.deliveries.count) deliveries inside quiet hours."
            : "\(run.quietHourViolations) of \(run.deliveries.count) deliveries inside quiet hours (outlined), in hours \(bad.map(String.init).joined(separator: ", "))."
        return """
            <h3>\(esc(title))</h3>
            <p class="takeaway">\(takeaway)</p>
            <svg viewBox="0 0 \(w) \(h)" role="img" aria-label="\(esc(title))">\(svg)</svg>
            """
    }

    // MARK: View 4, cap sweep

    static func sweepChart(_ r: Results) -> String {
        let w = 640.0, h = 280.0, left = 48.0, right = 70.0, bottom = 36.0, top = 12.0
        let all = r.pooledSweep.flatMap { p in Results.driftRings.map { p.stats($0).p90Wait } }
        let yMax = niceMax(all.max()!)
        func y(_ v: Double) -> Double { top + (h - top - bottom) * (1 - v / yMax) }
        func x(_ cap: Int) -> Double { left + 10 + (w - left - right - 10) * Double(cap - 1) / 9 }
        var svg = axisY(yMax: yMax, y: y, left: left, width: w - right, label: "p90 wait (days)")
        svg += "<line x1=\"\(x(r.defaultCap))\" x2=\"\(x(r.defaultCap))\" y1=\"\(top)\" y2=\"\(y(0))\" class=\"default\"/>"
        svg += "<text x=\"\(x(r.defaultCap) + 4)\" y=\"\(top + 10)\" class=\"lbl\">default</text>"
        var labelYs: [Double] = []
        for ring in Results.driftRings {
            let style = ringStyle[ring]!
            let pts = r.pooledSweep.map { (x($0.cap), y(Double($0.stats(ring).p90Wait))) }
            svg +=
                "<polyline points=\"\(pts.map { "\($0.0),\($0.1)" }.joined(separator: " "))\" fill=\"none\" stroke=\"var(\(style.cssVar))\" stroke-width=\"2\" stroke-dasharray=\"\(style.dash)\"/>"
            for (p, xy) in zip(r.pooledSweep, pts) {
                let s = p.stats(ring)
                svg +=
                    "<circle cx=\"\(xy.0)\" cy=\"\(xy.1)\" r=\"4\" fill=\"var(\(style.cssVar))\" class=\"pick\" data-cap=\"\(p.cap)\" data-tip=\"\(ring.name) ring, cap \(p.cap): p90 \(s.p90Wait) d, max \(s.maxWait) d, \(s.neverNudged) of \(s.episodes) episodes never nudged\"/>"
            }
            var ly = pts.last!.1 + 4
            while labelYs.contains(where: { abs($0 - ly) < 12 }) { ly += 12 }
            labelYs.append(ly)
            svg += "<text x=\"\(pts.last!.0 + 16)\" y=\"\(ly)\" class=\"lbl\">\(ring.name)</text>"
        }
        for cap in NudgeSettings.capRange {
            svg += "<text x=\"\(x(cap))\" y=\"\(h - 18)\" text-anchor=\"middle\" class=\"lbl\">\(cap)</text>"
        }
        svg += "<text x=\"\(x(5))\" y=\"\(h - 2)\" text-anchor=\"middle\" class=\"lbl\">daily cap (nudges per day)</text>"
        let legend = Results.driftRings.map { ring in
            let s = ringStyle[ring]!
            return
                "<span><svg width=\"26\" height=\"10\"><line x1=\"0\" x2=\"26\" y1=\"5\" y2=\"5\" stroke=\"var(\(s.cssVar))\" stroke-width=\"2\" stroke-dasharray=\"\(s.dash)\"/></svg> \(ring.name) ring</span>"
        }.joined(separator: " ")
        let rows = r.pooledSweep.map { p in
            "<tr><th scope=\"row\">\(p.cap)</th>"
                + Results.driftRings.map { "<td>\(p.stats($0).p90Wait)</td><td>\(p.stats($0).maxWait)</td>" }.joined()
                + "<td>\(p.meanNudgesPerDay)</td></tr>"
        }.joined()
        let head =
            "<tr><th scope=\"col\">Cap</th>"
            + Results.driftRings.map { "<th scope=\"col\">\($0.name) p90</th><th scope=\"col\">\($0.name) max</th>" }.joined()
            + "<th scope=\"col\">Nudges per day</th></tr>"
        return
            "<div class=\"legend\">\(legend)</div><svg viewBox=\"0 0 \(w) \(h)\" role=\"img\" aria-label=\"p90 wait by daily cap, one line per ring\">\(svg)</svg><details><summary>Table</summary><div class=\"scroll\"><table><thead>\(head)</thead><tbody>\(rows)</tbody></table></div></details>"
    }

